<#
.SYNOPSIS
  Rebuilds the whole PostgreSQL layer (schemas, tables, constraints, load, views, validation, KPI reconciliation) from the SQL scripts.

.DESCRIPTION
  Runs sql/00_build_all.sql with psql from the PROJECT ROOT (the \copy paths in the scripts are relative to it).
  DESTRUCTIVE for the schemas stg, core, analytics, qa and sandbox of the target database; other schemas are untouched.
  All data is SYNTHETIC (sampled simulation: 768 of 19,708 scheduled runs). Not IRCTC data.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File sql\run_all.ps1
  powershell -ExecutionPolicy Bypass -File sql\run_all.ps1 -User postgres -Port 5432 -Force

.NOTES
  Password: set $env:PGPASSWORD first, or let psql prompt, or use a pgpass.conf file.
  Written for PostgreSQL 18.4 on Windows (service postgresql-x64-18); developed and tested against PostgreSQL 16 on Linux.
#>
[CmdletBinding()]
param(
    [string]$PgHost   = "localhost",
    [int]   $Port     = 5432,
    [string]$User     = "postgres",
    [string]$Database = "irctc_analytics",
    [string]$PsqlPath = "",
    [string]$ServiceName = "postgresql-x64-18",
    [switch]$Force,
    [switch]$SkipServiceCheck
)
$ErrorActionPreference = "Stop"
$ProjectRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
Set-Location $ProjectRoot

# 1. locate psql: explicit path, PATH, then the default install folders (highest version first)
if (-not $PsqlPath) {
    $cmd = Get-Command psql -ErrorAction SilentlyContinue
    if ($cmd) { $PsqlPath = $cmd.Source }
    else {
        $found = Get-ChildItem "C:\Program Files\PostgreSQL\*\bin\psql.exe" -ErrorAction SilentlyContinue | Sort-Object { [int]($_.Directory.Parent.Name) } -Descending | Select-Object -First 1
        if ($found) { $PsqlPath = $found.FullName }
    }
}
if (-not $PsqlPath -or -not (Test-Path $PsqlPath)) { throw "psql.exe not found. Add the PostgreSQL bin folder to PATH or pass -PsqlPath." }
Write-Host "psql: $PsqlPath"
& $PsqlPath --version

# 2. service check (information only; starting a service needs an administrator prompt)
if (-not $SkipServiceCheck) {
    $svc = Get-Service -Name $ServiceName -ErrorAction SilentlyContinue
    if ($svc) {
        Write-Host "Service $ServiceName : $($svc.Status)"
        if ($svc.Status -ne "Running") { throw "Service $ServiceName is not running. Start it (Start-Service $ServiceName, as administrator) and re-run." }
    } else { Write-Warning "Service $ServiceName not found on this machine (remote server or a different service name?). Continuing." }
}

# 3. the cleaned data must exist (it is generated by python python/src/pipeline.py and is not stored in Git)
foreach ($f in "stations","routes","trains","train_stops","calendar","seat_capacity","train_operations","bookings","booking_passengers","cancellations") {
    if (-not (Test-Path "data/processed/cleaned/$f.csv")) { throw "Missing data/processed/cleaned/$f.csv. Run: python python/src/pipeline.py" }
}

# 4. confirmation (the build drops and recreates five schemas)
if (-not $Force) {
    Write-Host ""
    Write-Host "This DROPS and recreates the schemas stg, core, analytics, qa and sandbox in database '$Database' on ${PgHost}:$Port." -ForegroundColor Yellow
    $answer = Read-Host "Type YES to continue"
    if ($answer -ne "YES") { Write-Host "Cancelled. Nothing was changed."; exit 1 }
}

# 5. build (UTF-8 client encoding so the en dash in train names loads correctly)
$env:PGCLIENTENCODING = "UTF8"
& $PsqlPath -X -h $PgHost -p $Port -U $User -d $Database -v ON_ERROR_STOP=1 -f "sql/00_build_all.sql"
if ($LASTEXITCODE -ne 0) { throw "Build failed (psql exit code $LASTEXITCODE). Nothing after the failing statement was run." }
Write-Host "Build finished. Results: reports/phase4_check_results.csv and reports/phase4_kpi_reconciliation.csv" -ForegroundColor Green
